package com.todokanai.composepracticenew.model

/** 앱 설정(정렬 기준·마지막 접속 서버 등) 저장소에서 일어난 실패. 설정이 바뀌지 않았거나 기본값으로 보이는 이유를 사용자에게 알리는 데 쓴다. */
enum class PreferenceFailure {
    /** 설정을 읽지 못해 저장된 값 대신 기본값으로 동작한다. 저장소가 다시 읽히면 저장된 값으로 돌아온다. 읽기 실패를 결과로 돌려받는 호출(예: 마지막 서버 id 읽기)은 여기에 포함되지 않는다. */
    READ,

    /** 설정 변경을 저장하지 못해 이전 값이 그대로 남았다. */
    SAVE,

    /** 설정 파일이 손상돼 읽을 수 없어, 빈 설정으로 바꿨다. 저장돼 있던 값은 모두 기본값으로 돌아갔다. */
    RESET
}
